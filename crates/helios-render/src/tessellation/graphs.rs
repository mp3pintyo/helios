//! Material graphs that drive displacement, in the tessellation passes (UE: the material's
//! Displacement output feeds Nanite tessellation).
//!
//! One dispatch processes the displaced clusters of every material at once, so the dicing
//! pipelines cannot be specialised per material as the G-buffer resolve is. Instead the scene's
//! set of displacing graphs — those some displaced material takes its height from — makes one
//! *permutation* of the dicing pipelines: a generated module (in place of
//! `displacement_graphs_off.wgsl`) holds every such graph's `graph_displacement` code under its
//! graph id and a switch on the material's graph id (`TessMaterial::source.z`), which also knows
//! whether the graph's value is a height or a vector. Permutations are
//! compiled at runtime (natively and in the browser) and cached by the hash of the set, so editing
//! a graph's displacement compiles one, changing its parameters (the parameter block, bound at
//! [`BINDING_GRAPH_PARAMETERS`]) compiles nothing, and scenes without displacing graphs keep the
//! base pipelines. Only the dicing reads heights: emit, split and their argument passes are shared.

use crate::material_graphs::MaterialGraphHandle;
use crate::scene::Scene;
use crate::substrate_gpu::GRAPH_PARAMETER_SLOTS;
use helios_material::DisplacementKind;

use super::{displacement_source, DisplacementSource};

/// Bindings of the dicing passes that graph code reads: the material albedo array (texture
/// samples' colour) and the graph parameter block.
pub const BINDING_ALBEDO: u32 = 42;
pub const BINDING_GRAPH_PARAMETERS: u32 = 68;

/// The graph id of `TessMaterial::source.z` (0: the height is a texture's).
pub fn graph_id(graph: MaterialGraphHandle) -> u32 {
    graph.index() + 1
}

/// The graphs displaced materials take their height from: (graph id, displacement code hash),
/// sorted and without duplicates — the key of a dicing permutation.
pub fn displacing_graphs(scene: &Scene) -> Vec<(u32, u64)> {
    let mut set: Vec<(u32, u64)> = scene
        .materials
        .iter()
        .filter_map(|m| match displacement_source(scene, m)? {
            DisplacementSource::Graph(g) => Some((graph_id(g), scene.compiled_material_graph(g)?.displacement_hash()?)),
            DisplacementSource::Texture(_) => None,
        })
        .collect();
    set.sort_unstable();
    set.dedup();
    set
}

/// The generated module of a permutation: every graph's displacement function and the switch
/// `displacement_value` (displacement_height.wgsl) calls. `functions`: (graph id, what its
/// function returns, code of `CompiledGraph::displacement_function` named
/// `displacement_graph_<id>`).
pub fn dispatch_module(functions: &[(u32, DisplacementKind, String)]) -> String {
    let mut code = String::from(
        "// Material graphs that drive displacement (generated by tessellation/graphs.rs).\n\
         #include \"displacement_graph.wgsl\"\n\n",
    );
    code.push_str(&format!("@group(0) @binding({BINDING_ALBEDO}) var material_albedo: texture_2d_array<f32>;\n"));
    code.push_str(&format!("@group(0) @binding({BINDING_GRAPH_PARAMETERS}) var<uniform> graph_params: array<vec4<f32>, {GRAPH_PARAMETER_SLOTS}>;\n\n"));
    // The tessellation passes have no motion vectors to write.
    code.push_str("const DISPLACEMENT_ANIMATED: bool = false;\n\n");
    for (_, _, function) in functions {
        code.push_str(function);
        code.push('\n');
    }
    code.push_str("fn displacement_graph_value(graph: u32, material: u32, params: u32, max_scale: f32, p: DisplacementInput) -> DisplacementValue {\n");
    code.push_str("    let m = materials[material];\n    let input = displacement_surface(material, max_scale, p);\n    switch graph {\n");
    for (id, kind, _) in functions {
        let wrap = match kind {
            DisplacementKind::Height => "displacement_from_height",
            DisplacementKind::Vector => "displacement_from_vector",
        };
        code.push_str(&format!("        case {id}u: {{ return {wrap}(displacement_graph_{id}(m, input, params)); }}\n"));
    }
    code.push_str("        default: { return displacement_from_height(tess.materials[material].params.y); }\n    }\n}\n");
    code
}

/// The permutation module of `set` (see [`displacing_graphs`]) for `scene`'s graphs.
pub fn scene_dispatch_module(scene: &Scene, set: &[(u32, u64)]) -> String {
    let functions: Vec<(u32, DisplacementKind, String)> = set
        .iter()
        .filter_map(|&(id, _)| {
            let compiled = scene.compiled_material_graph(scene.material_graph_handle(id - 1)?)?;
            Some((id, compiled.displacement_kind, compiled.displacement_function(&format!("displacement_graph_{id}"))?))
        })
        .collect();
    dispatch_module(&functions)
}

/// FNV-1a of a permutation key.
pub fn set_hash(set: &[(u32, u64)]) -> u64 {
    set.iter().flat_map(|&(id, hash)| (id as u64).to_le_bytes().into_iter().chain(hash.to_le_bytes())).fold(0xcbf29ce484222325u64, |h, b| (h ^ b as u64).wrapping_mul(0x100000001b3))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Displacement, Material};
    use helios_material::presets;

    #[test]
    fn the_permutation_follows_the_displaced_materials_graphs() {
        let mut scene = Scene::new();
        let bricks = scene.add_material_graph(presets::brick_pavement());
        let lava = scene.add_material_graph(presets::lava());
        let displaced = Material { displacement: Some(Displacement::height(0.03, 0.9)), ..Material::default() };
        scene.add_material(Material { graph: Some(lava), ..displaced });
        assert!(displacing_graphs(&scene).is_empty(), "a graph without a Displacement output does not displace");
        let material = scene.add_material(Material { graph: Some(bricks), ..Material::default() });
        assert!(displacing_graphs(&scene).is_empty(), "without a magnitude the graph's height moves nothing");
        scene.set_material(material, Material { graph: Some(bricks), ..displaced });
        let set = displacing_graphs(&scene);
        let hash = scene.compiled_material_graph(bricks).unwrap().displacement_hash().unwrap();
        assert_eq!(set, [(graph_id(bricks), hash)]);
        let code = scene_dispatch_module(&scene, &set);
        assert!(code.contains("fn displacement_graph_1(m: Material, input: DisplacementSurface, params: u32) -> f32"), "{code}");
        assert!(code.contains("case 1u: { return displacement_from_height(displacement_graph_1(m, input, params)); }"), "{code}");
        // A second material of the same graph shares its code.
        scene.add_material(Material { graph: Some(bricks), ..displaced });
        assert_eq!(displacing_graphs(&scene), set);
        assert_ne!(set_hash(&set), set_hash(&[]));
    }
}
